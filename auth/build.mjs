// Bundles hookline-auth.jsx (+ React 19, Privy, viem) for the browser into ../game/hookline-auth/
// as ES modules with code splitting: the entry + its static imports are ~1.8 MB, and Privy's optional
// wallet connectors (WalletConnect/Reown, Coinbase, Solana, ...) stay in lazy chunks that a Google/email
// login never fetches. (A single IIFE was ~6 MB.) hookline-real.js loads hookline-auth/hookline-auth.js
// with <script type="module">.
// Run: cd auth && npm install && npm run build   (commit the output; Railway never runs this)
import { build } from 'esbuild';
import { rmSync, readdirSync, statSync } from 'node:fs';

const outdir = new URL('../game/hookline-auth/', import.meta.url).pathname;
rmSync(outdir, { recursive: true, force: true });
await build({
  entryPoints: { 'hookline-auth': new URL('./hookline-auth.jsx', import.meta.url).pathname },
  outdir,
  bundle: true,
  splitting: true,
  format: 'esm',
  platform: 'browser',
  target: ['es2020', 'safari15'],
  minify: true,
  legalComments: 'none',
  chunkNames: 'c/[hash]',
  jsx: 'automatic',
  define: { 'process.env.NODE_ENV': '"production"', global: 'globalThis' },
  banner: { js: '/* HookLine auth island (Privy). Generated by auth/build.mjs: do not edit. */' },
  logLevel: 'warning',
});
let n = 0, bytes = 0;
const walk = d => { for (const f of readdirSync(d)) { const p = d + '/' + f; const s = statSync(p); if (s.isDirectory()) walk(p); else { n++; bytes += s.size; } } };
walk(outdir);
console.log(`wrote ${outdir} (${n} files, ${(bytes / 1024).toFixed(0)} KB total; entry ${(statSync(outdir + 'hookline-auth.js').size / 1024).toFixed(0)} KB)`);
